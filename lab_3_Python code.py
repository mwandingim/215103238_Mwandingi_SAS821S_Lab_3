def clean_text(text):
    """
    Basic reproducible text normalisation.

    Operations:
      - convert missing values to empty strings
      - convert to lower case
      - replace URLs with the token 'url'
      - remove punctuation while retaining useful word characters
      - collapse repeated whitespace
    """
    if pd.isna(text):
        return ""

    text = str(text).lower()

    text = re.sub(
        r"https?://\S+|www\.\S+",
        " url ",
        text
    )

    text = re.sub(
        r"[^a-z0-9_\-\s]",
        " ",
        text
    )

    text = re.sub(
        r"\s+",
        " ",
        text
    ).strip()

    return text


