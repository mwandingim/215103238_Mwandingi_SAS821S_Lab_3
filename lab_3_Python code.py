def adjusted_edge_probability(edge, scenario):
    p = float(edge["base_transmission_probability"])
    target = edge["target_asset"]
    source_zone = edge["source_zone"]
    target_zone = edge["target_zone"]

    # Patch vendor laptop, VPN gateway and vendor broker.
    if scenario["patch_factor"] < 1 and target in VENDOR_PATH_ASSETS:
        p *= float(scenario["patch_factor"])

    # Reduce DMZ-to-OT/OT-DMZ and OT lateral movement.
    if scenario["segmentation_factor"] < 1:
        dmz_to_ot = (
            source_zone in {"DMZ", "OT-DMZ"}
            and target_zone in {"OT-DMZ", "OT"}
        )
        ot_lateral = source_zone == "OT" and target_zone == "OT"
        if dmz_to_ot or ot_lateral:
            p *= float(scenario["segmentation_factor"])

    return min(max(p, 0.0), 1.0)

def simulate_once(scenario, rng):
    infected = {INITIAL_INFECTED: 0}
    newly_infected = [INITIAL_INFECTED]
    step = 0
    time_to_ot = None
    safety_reached = False

    while newly_infected and step < MAX_STEPS:
        step += 1
        new_assets = []

        for source in list(infected):
            infection_step = infected[source]

            for _, edge in edges[edges["source_asset"] == source].iterrows():
                target = edge["target_asset"]

                if target in infected:
                    continue

                probability = adjusted_edge_probability(edge, scenario)

                # Rapid isolation applies to compromised Windows sources.
                source_os = str(posture_map[source]["operating_system"])
                delay = int(scenario["isolation_delay_steps"])

                if "Windows" in source_os and delay < 99:
                    elapsed = step - infection_step
                    if elapsed >= delay:
                        probability *= float(
                            scenario["post_detection_transmission_factor"]
                        )

                if rng.random() < probability:
                    infected[target] = step
                    new_assets.append(target)

                    if asset_map[target]["zone"] == "OT" and time_to_ot is None:
                        time_to_ot = step

                    if asset_map[target]["zone"] == "Safety":
                        safety_reached = True

        newly_infected = new_assets

    return {
        "ot_reached": any(asset_map[a]["zone"] == "OT" for a in infected),
        "safety_reached": safety_reached,
        "critical_assets_infected": sum(
            asset_map[a]["criticality"] == "Critical" for a in infected
        ),
        "total_assets_infected": len(infected),
        "time_to_ot": time_to_ot,
    }

run_rows = []

for _, scenario in scenarios.iterrows():
    scenario_number = int(str(scenario["scenario_id"])[1:])
